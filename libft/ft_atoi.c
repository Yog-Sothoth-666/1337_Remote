#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int					i;
	unsigned long long	n;
	int					s;

	i = 0;
	s = 1;
	n = 0;
	while ((nptr[i] >= 9 && nptr[i] <= 13) || nptr[i] == ' ')
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			s = -1;
		i++;
	}
	while (ft_isdigit(nptr[i]))
	{
		n *= 10;
		n += nptr[i] - '0';
		i++;
	}
	if (s == -1)
		return ((int)-n);
	return ((int)n);
}
